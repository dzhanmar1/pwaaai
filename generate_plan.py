from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

def add_stage(doc, slide_num, title, teacher_action, ai_speech, teacher_speech):
    h = doc.add_heading(f'Слайд {slide_num}: {title}', level=2)
    h.runs[0].font.color.rgb = RGBColor(42, 157, 143) # accent-green
    
    # Действие учителя (техническое)
    p = doc.add_paragraph()
    p.add_run('🛠 Действие: ').bold = True
    p.add_run(teacher_action).italic = True
    
    # Реплика ИИ
    p = doc.add_paragraph()
    p.add_run('🤖 ИИ-Ассистент: ').bold = True
    p.add_run(f'«{ai_speech}»')
    
    # Слова/Действия Учителя
    p = doc.add_paragraph()
    p.add_run('👩‍🏫 Учитель: ').bold = True
    p.add_run(teacher_speech)
    
    doc.add_paragraph('_' * 70) # Разделитель

