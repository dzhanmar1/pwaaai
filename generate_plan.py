from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

def create_lesson_plan():
    doc = Document()
    
    # Заголовок
    title = doc.add_heading('Тематический план (Конспект открытого урока)', 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    
    # Шапка
    p = doc.add_paragraph()
    p.add_run('Дата: ').bold = True
    p.add_run('____________________\n')
    p.add_run('Класс: ').bold = True
    p.add_run('7 «А»\n')
    p.add_run('Предмет: ').bold = True
    p.add_run('Русский язык и литература\n')
    p.add_run('ФИО учителя: ').bold = True
    p.add_run('____________________\n')
    p.add_run('Формат: ').bold = True
    p.add_run('Интерактивный открытый урок с применением ИИ-ассистента и веб-презентации.\n')
    p.add_run('Оборудование: ').bold = True
    p.add_run('Интерактивная панель (или проектор), компьютер, аудиосистема (колонки), карточки для жеребьевки («Компас» и «Циркуль»), индивидуальные оценочные листы, ватманы, маркеры.\n')
    
    # Тема и Цели
    doc.add_heading('Тема урока:', level=1)
    p = doc.add_paragraph()
    p.add_run('Ю.О. Домбровский «Хранитель древностей» (Алматы — город-сад).').bold = True
    
    doc.add_heading('Цели обучения:', level=1)
    ul = doc.add_paragraph(style='List Bullet')
    ul.add_run('Понимать содержание художественного текста, определяя главную и второстепенную информацию.')
    ul = doc.add_paragraph(style='List Bullet')
    ul.add_run('Анализировать средства выразительности (эпитеты, сравнения, метафоры), использованные автором для создания образа Алма-Аты 30-х годов.')
    ul = doc.add_paragraph(style='List Bullet')
    ul.add_run('Формировать навыки работы в команде, презентации и защиты своих идей (через создание постеров).')
    
    doc.add_heading('Ход урока', level=1)
    
    stages = [
        ("1. Организационный момент (Слайд 1-2)", 
         "• ИИ-ассистент приветствует класс и объявляет тему.\n• Учитель настраивает детей на работу (Психологический тренинг «Улыбнитесь друг другу»)."),
        ("2. Деление на группы и правила работы (Слайд 3-4)", 
         "• Учащиеся выбирают карточки на столе: «Циркуль» (Архитекторы) или «Компас» (Путешественники) и делятся на 2 команды.\n• Повторение правил работы в команде (Слушай, Вполголоса, Участвуй)."),
        ("3. Оценочные листы (Слайд 5)", 
         "• Ученики берут физические оценочные листы со своих парт.\n• ИИ-ассистент просит честно оценивать свой личный вклад на каждом этапе."),
        ("4. Проверка домашнего задания (Слайд 6)", 
         "• Проверка знания романа В. Обручева «Земля Санникова».\n• Обсуждение задания «Дерево предсказаний»: ученики делятся своими вариантами концовки и сравнивают с авторской."),
        ("5. Введение в новую тему (Слайд 7-8)", 
         "• Знакомство со старой Алма-Атой через призму романа Ю. Домбровского.\n• Чтение и анализ отрывка о контрасте хмурой Москвы и буйства красок Алма-Аты. Фронтальная беседа о художественных средствах (Задания 1, 2)."),
        ("6. Творение человека (Слайд 9)", 
         "• Рассказ ИИ о Вознесенском кафедральном соборе (инж. А. Зенков) и землетрясении 1911 года.\n• Чтение по ролям разговора со сторожем. Поиск эпитетов в тексте (Задания 5, 6)."),
        ("7. Физминутка (Слайд 10)", 
         "• Динамическая пауза с видео («Алматинские тополя»). Разминка."),
        ("8. Обобщение: Ассоциативный куст (Слайд 11)", 
         "• Учащиеся подбирают ассоциации к образу Алматы 30-х годов.\n• Учитель на интерактивной доске открывает карточки (Город-сад, А. Зенков, Апорт и т.д.), резюмируя ответы класса."),
        ("9. Творческая работа: Защита постеров (Слайд 12)", 
         "• Команды создают постеры на тему «Алматы — город-сад».\n• Запускается интерактивный таймер с аудио-предупреждениями от ИИ (осталось 2 минуты, время вышло).\n• Защита проектов перед классом."),
        ("10. Рефлексия и Домашнее задание (Слайд 13)", 
         "• Оценка эмоционального состояния через интерактивное «Дерево чувств».\n• ИИ-ассистент и учитель объявляют домашнее задание: написание синквейна и эссе из блока УС.")
    ]
    
    for stage_title, stage_content in stages:
        doc.add_heading(stage_title, level=2)
        doc.add_paragraph(stage_content)
        
    doc.save('d:/projects/np/План_Урока_Домбровский.docx')
    print("Document created successfully.")

create_lesson_plan()
